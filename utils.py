"""Four-source entity tables, indexed batches and portable training checkpoints.

This module does not import PyG, create a model, or run training on import.
Graph/embedding banks are read-only ordinary Python objects, not model buffers.
"""
from pathlib import Path
from types import SimpleNamespace
import csv
import hashlib
import json
import random

import numpy as np
import torch
import torch.nn as nn

class FourSourceSplit:
    """Load entities once; after GPU upload, retain indices, labels, and IDs for CSV export."""
    def __init__(self, path, expected_split, dataset=None, protein_embedding_dim=640):
        self.data = torch.load(path, map_location='cpu', weights_only=True, mmap=True)
        if self.data.get('format_version') != 4:
            raise ValueError(f'{path}: expected a v4 split file generated by create_data.py')
        self.dataset = self.data.get('dataset')
        if (self.dataset not in ('davis', 'kiba') or self.data.get('split') != expected_split
                or (dataset is not None and self.dataset != dataset)):
            raise ValueError(f'{path}: dataset/split does not match {dataset or "davis/kiba"} {expected_split}')
        self.ligand_ids = self.data['ligand_ids']
        self.protein_ids = self.data['protein_ids']
        self.pairs = self.data['pairs']
        self.labels = self.pairs['y'].float().reshape(-1)
        n = len(self.labels)
        if (self.pairs['y'].ndim != 1 or n == 0 or len(self.pairs['ligand_index']) != n
                or len(self.pairs['protein_index']) != n or len(self.pairs['row_id']) != n
                or not torch.isfinite(self.labels).all()):
            raise ValueError(f'{path}: invalid pair or label tables')
        nl, np_ = len(self.data['ligand_ids']), len(self.data['protein_ids'])
        if (len(self.data['ligand_graphs']) != nl or len(self.data['ligand_embeddings']) != nl
                or len(self.data['protein_graphs']) != np_
                or len(self.data['protein_embeddings']) != np_
                or len(self.data['protein_embedding_ids']) != np_
                or len(set(self.ligand_ids)) != nl or len(set(self.protein_ids)) != np_):
            raise ValueError(f'{path}: four-source table dimensions do not match')
        for key, size in [('ligand_index', nl), ('protein_index', np_)]:
            indices = self.pairs[key]
            if (indices.dtype != torch.long or indices.shape != (n,)
                    or indices.min() < 0 or indices.max() >= size):
                raise ValueError(f'{path}: invalid {key} indices')
        # Both sources contain unpadded token matrices; normalize dtype once per entity.
        for key, width in [('ligand_embeddings', 512),
                           ('protein_embeddings', protein_embedding_dim)]:
            for i, value in enumerate(self.data[key]):
                if (not isinstance(value, torch.Tensor) or value.ndim != 2
                        or value.shape[0] == 0 or value.shape[1] != width
                        or not value.is_floating_point() or not torch.isfinite(value).all()):
                    raise ValueError(f'{path}: {key}[{i}] must be finite with shape [L>0,{width}]')
                self.data[key][i] = value.detach().float()

    def __len__(self):
        return len(self.labels)

    def pair_ids(self, index):
        li = int(self.pairs['ligand_index'][index])
        pi = int(self.pairs['protein_index'][index])
        return self.ligand_ids[li], self.protein_ids[pi]


def pack_segments(values):
    """Concatenate segments once on CPU and store offsets without padding or pooling tokens."""
    lengths = torch.tensor([value.shape[0] for value in values], dtype=torch.long)
    ptr = torch.cat((torch.zeros(1, dtype=torch.long), lengths.cumsum(0)))
    return torch.cat(values, dim=0).contiguous(), ptr


def pack_graphs(graphs, width):
    for graph in graphs:
        x, edges = graph['x'], graph['edge_index']
        if (x.ndim != 2 or x.shape[0] == 0 or x.shape[1] != width
                or not torch.isfinite(x).all() or edges.ndim != 2 or edges.shape[0] != 2
                or edges.dtype != torch.long
                or (edges.numel() and (edges.min() < 0 or edges.max() >= len(x)))):
            raise ValueError(f'Graph requires finite x with shape [N>0,{width}] and valid edge_index')
    x, node_ptr = pack_segments([graph['x'].detach().float() for graph in graphs])
    # Edges store LOCAL node indices; add offsets only when selecting graphs for a batch.
    edges, edge_ptr = pack_segments([graph['edge_index'].t() for graph in graphs])
    return {'x': x, 'node_ptr': node_ptr, 'edges': edges, 'edge_ptr': edge_ptr}


def same_graph(a, b):
    return torch.equal(a['x'], b['x']) and torch.equal(a['edge_index'], b['edge_index'])


def build_cpu_tables(splits):
    """Merge train/test entities; use original graph IDs and sequence-hash protein embedding IDs."""
    if len({split.dataset for split in splits}) != 1:
        raise ValueError('DAVIS and KIBA cannot share one bank')
    ligands, proteins, protein_embeddings = {}, {}, {}
    for split in splits:
        data = split.data
        for i, lid in enumerate(split.ligand_ids):
            graph, embedding = data['ligand_graphs'][i], data['ligand_embeddings'][i]
            if lid in ligands:
                old_graph, old_embedding = ligands[lid]
                if not same_graph(old_graph, graph) or not torch.equal(old_embedding, embedding):
                    raise ValueError(f'Ligand {lid}: train/test data differ')
            else:
                ligands[lid] = (graph, embedding)
        for i, pid in enumerate(split.protein_ids):
            graph = data['protein_graphs'][i]
            eid = data['protein_embedding_ids'][i]
            embedding = data['protein_embeddings'][i]
            if pid in proteins:
                old_graph, old_eid = proteins[pid]
                if old_eid != eid or not same_graph(old_graph, graph):
                    raise ValueError(f'Protein {pid}: train/test data differ')
            else:
                proteins[pid] = (graph, eid)
            if eid in protein_embeddings:
                if not torch.equal(protein_embeddings[eid], embedding):
                    raise ValueError(f'Embedding {eid}: same ID has different values')
            else:
                protein_embeddings[eid] = embedding
    ligand_ids, protein_ids, embedding_ids = sorted(ligands), sorted(proteins), sorted(protein_embeddings)
    ligand_map = {key: i for i, key in enumerate(ligand_ids)}
    protein_map = {key: i for i, key in enumerate(protein_ids)}
    embedding_map = {key: i for i, key in enumerate(embedding_ids)}
    tables = {}
    for prefix, graphs, width in (
            ('ligand', [ligands[key][0] for key in ligand_ids], 78),
            ('protein', [proteins[key][0] for key in protein_ids], 41)):
        for key, value in pack_graphs(graphs, width).items():
            tables[f'{prefix}_{key}'] = value
    tables['ligand_embedding'], tables['ligand_embedding_ptr'] = pack_segments(
        [ligands[key][1] for key in ligand_ids])
    tables['protein_embedding'], tables['protein_embedding_ptr'] = pack_segments(
        [protein_embeddings[key] for key in embedding_ids])
    tables['protein_to_embedding'] = torch.tensor(
        [embedding_map[proteins[key][1]] for key in protein_ids], dtype=torch.long)
    return tables, ligand_map, protein_map


def execution_devices(device, use_data_parallel=True, max_gpus=2):
    """Put the primary GPU first; default to at most two GPUs, with single-GPU/CPU fallback."""
    device = torch.device(device)
    if max_gpus < 1:
        raise ValueError('MAX_GPUS must be >= 1')
    if device.type != 'cuda':
        return [device]
    count = torch.cuda.device_count()
    primary = device.index if device.index is not None else torch.cuda.current_device()
    if not 0 <= primary < count:
        raise ValueError(f'Primary GPU cuda:{primary} is not among the {count} available GPUs')
    ids = [primary]
    if use_data_parallel:
        ids += [i for i in range(count) if i != primary]
    return [torch.device('cuda', i) for i in ids[:max_gpus]]


def take_segments(values, ptr, indices):
    """Look up segments and build batch vectors on the bank's device (GPU during training)."""
    starts = ptr.index_select(0, indices)
    lengths = ptr.index_select(0, indices + 1) - starts
    batch_ptr = torch.cat((lengths.new_zeros(1), lengths.cumsum(0)))
    owners = torch.repeat_interleave(torch.arange(indices.numel(), device=indices.device), lengths)
    local = torch.arange(owners.numel(), device=indices.device) - batch_ptr.index_select(0, owners)
    positions = starts.index_select(0, owners) + local
    return values.index_select(0, positions), owners, batch_ptr


class DeviceFourSourceStore:
    """Each GPU holds a tensor dictionary; replicas share a read-only Python store."""
    def __init__(self, cpu_tables, devices, ligand_map, protein_map):
        self.devices = tuple(torch.device(device) for device in devices)
        if not self.devices or len(set(self.devices)) != len(self.devices):
            raise ValueError('Expected a non-empty list of distinct devices')
        self.device = self.devices[0]  # Pair indices and labels reside on the primary GPU.
        self.ligand_id_to_index = ligand_map
        self.protein_id_to_index = protein_map
        self.nbytes = sum(value.numel() * value.element_size() for value in cpu_tables.values())
        self.tables = {}
        for target in self.devices:
            if target.type == 'cuda':
                free, _ = torch.cuda.mem_get_info(target)
                if self.nbytes > free:
                    raise RuntimeError(f'Bank on {target} requires {self.nbytes / 1024**3:.3f} GiB, '
                                       f'but only {free / 1024**3:.3f} GiB is free. Restart the session to release the old bank.')
            # Upload once per GPU. The bank is not a model buffer, so DataParallel
            # does not broadcast/copy it on each forward pass, and checkpoints exclude it.
            self.tables[str(target)] = {
                key: value.detach().to(target) for key, value in cpu_tables.items()}
            print(f'Four sources on {target}: {self.nbytes / 1024**3:.3f} GiB; '
                  f'{len(ligand_map)} ligand graphs, {len(protein_map)} protein graphs, '
                  f'{cpu_tables["protein_embedding_ptr"].numel() - 1} protein embeddings')

    def on(self, device):
        key = str(torch.device(device))
        if key not in self.tables:
            raise ValueError(f'Bank is not prepared on {key}')
        return self.tables[key]

    def graph_batch(self, prefix, indices):
        t = self.on(indices.device)
        x, batch, node_ptr = take_segments(t[f'{prefix}_x'], t[f'{prefix}_node_ptr'], indices)
        edges, edge_batch, _ = take_segments(t[f'{prefix}_edges'], t[f'{prefix}_edge_ptr'], indices)
        edge_index = (edges + node_ptr.index_select(0, edge_batch).unsqueeze(1)).t().contiguous()
        return x, edge_index, batch

    def lookup(self, pair_indices):
        # DataParallel splits INDICES; each replica looks up its local batch on the same device.
        t = self.on(pair_indices.device)
        li, pi = pair_indices[:, 0], pair_indices[:, 1]
        drug_x, drug_edges, drug_batch = self.graph_batch('ligand', li)
        prot_x, prot_edges, prot_batch = self.graph_batch('protein', pi)
        drug_embedding, drug_embedding_batch, _ = take_segments(
            t['ligand_embedding'], t['ligand_embedding_ptr'], li)
        embedding_indices = t['protein_to_embedding'].index_select(0, pi)
        protein_embedding, protein_embedding_batch, _ = take_segments(
            t['protein_embedding'], t['protein_embedding_ptr'], embedding_indices)
        # Tensors already reside on the GPU; wrap attributes without CPU collation or copying.
        return (SimpleNamespace(x=drug_x, edge_index=drug_edges, batch=drug_batch,
                     drug_embedding=drug_embedding, drug_embedding_batch=drug_embedding_batch),
                SimpleNamespace(x=prot_x, edge_index=prot_edges, batch=prot_batch,
                     protein_embedding=protein_embedding, protein_embedding_batch=protein_embedding_batch))


class IndexBatches:
    """Yield only GPU pair indices and labels per batch; do not fetch graphs/tokens on CPU."""
    def __init__(self, split, store, batch_size, shuffle=False, seed=42):
        if batch_size < 1:
            raise ValueError('Batch size must be >= 1')
        self.size, self.batch_size = len(split), batch_size
        self.shuffle, self.device = shuffle, store.device
        self.generator = torch.Generator(device=self.device).manual_seed(seed)
        ligand_remap = torch.tensor([store.ligand_id_to_index[key] for key in split.ligand_ids])
        protein_remap = torch.tensor([store.protein_id_to_index[key] for key in split.protein_ids])
        self.pairs = torch.stack((
            ligand_remap.index_select(0, split.pairs['ligand_index']),
            protein_remap.index_select(0, split.pairs['protein_index'])), dim=1).to(self.device)
        self.labels = split.labels.reshape(-1, 1).to(self.device)

    def __len__(self):
        return (self.size + self.batch_size - 1) // self.batch_size

    def reset_seed(self, seed):
        self.generator.manual_seed(seed)

    def __iter__(self):
        order = (torch.randperm(self.size, generator=self.generator, device=self.device)
                 if self.shuffle else torch.arange(self.size, device=self.device))
        for start in range(0, self.size, self.batch_size):
            rows = order[start:start + self.batch_size]
            yield self.pairs.index_select(0, rows), self.labels.index_select(0, rows)


def unwrap_model(model):
    return model.module if isinstance(model, nn.DataParallel) else model

def save_checkpoint(checkpoint, path):
    path = Path(path)
    temporary = path.with_name(path.name + '.tmp')
    try:
        torch.save(checkpoint, temporary)
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)

def save_test_predictions(path, dataset, labels, predictions):
    if not len(dataset) == len(labels) == len(predictions):
        raise ValueError('Test sample and prediction counts do not match')
    with Path(path).open('w', newline='', encoding='utf-8') as handle:
        writer = csv.writer(handle)
        writer.writerow(['row_id', 'ligand_id', 'protein_id', 'affinity', 'predicted_affinity'])
        for i, (label, prediction) in enumerate(zip(labels, predictions)):
            ligand_id, protein_id = dataset.pair_ids(i)
            writer.writerow([dataset.pairs['row_id'][i], ligand_id, protein_id,
                             float(label), float(prediction)])

def cpu_snapshot(value):
    if isinstance(value, torch.Tensor):
        return value.detach().cpu().clone()
    if isinstance(value, dict):
        return {key: cpu_snapshot(item) for key, item in value.items()}
    if isinstance(value, list):
        return [cpu_snapshot(item) for item in value]
    if isinstance(value, tuple):
        return tuple(cpu_snapshot(item) for item in value)
    return value

def dataset_signature(splits):
    # Validate pair/label order and IDs without rereading large embedding tensors.
    digest = hashlib.sha256()
    for split in splits:
        digest.update(json.dumps([split.ligand_ids, split.protein_ids],
                                 ensure_ascii=False).encode('utf-8'))
        for key in ('ligand_index', 'protein_index', 'y'):
            value = split.pairs[key].detach().cpu().contiguous()
            digest.update(str((key, tuple(value.shape), str(value.dtype))).encode())
            digest.update(value.numpy().tobytes())
    return digest.hexdigest()

def model_signature(model):
    core = unwrap_model(model)
    description = {
        'modules': [(name, ('__main__' if name == '' else type(module).__module__), type(module).__qualname__, repr(module))
                    for name, module in core.named_modules()],
        'state': [(key, list(value.shape), str(value.dtype))
                  for key, value in core.state_dict().items()],
    }
    return hashlib.sha256(json.dumps(description, sort_keys=True).encode()).hexdigest()

def capture_rng(batches, devices):
    numpy_state = np.random.get_state()
    return {
        'python': random.getstate(),
        'numpy': {'name': numpy_state[0], 'keys': numpy_state[1].tolist(),
                  'position': numpy_state[2], 'has_gauss': numpy_state[3],
                  'cached_gaussian': numpy_state[4]},
        'torch_cpu': torch.get_rng_state().clone(),
        'torch_cuda': [torch.cuda.get_rng_state(target).cpu()
                       for target in devices if target.type == 'cuda'],
        'batch_generator': batches.generator.get_state().cpu(),
        'batch_generator_device': str(batches.generator.device),
    }

def restore_rng(state, batches, devices):
    random.setstate(state['python'])
    ns = state['numpy']
    np.random.set_state((ns['name'], np.array(ns['keys'], dtype=np.uint32),
                         ns['position'], ns['has_gauss'], ns['cached_gaussian']))
    torch.set_rng_state(state['torch_cpu'])
    targets = [target for target in devices if target.type == 'cuda']
    if len(targets) == len(state['torch_cuda']):
        for target, value in zip(targets, state['torch_cuda']):
            torch.cuda.set_rng_state(value, target)
    else:
        print('GPU count changed: keeping the new session CUDA seed; exact replay is unavailable.')
    saved_type = torch.device(state['batch_generator_device']).type
    if saved_type == torch.device(batches.generator.device).type:
        batches.generator.set_state(state['batch_generator'])
    else:
        print('CPU/CUDA generator changed: keeping the new session shuffle seed.')

def resume_problem(payload, expected):
    if not isinstance(payload, dict) or payload.get('checkpoint_kind') != 'training_resume_v1':
        return 'not a full resume checkpoint (old best/weights file lacks optimizer/RNG state)'
    required = ('model_state_dict', 'optimizer_state_dict', 'epoch', 'best_checkpoint',
                'history', 'rng_state', 'best_predictions')
    if any(key not in payload for key in required):
        return 'missing training state'
    for key, value in expected.items():
        if payload.get(key) != value:
            return f'{key} differs from the current run'
    epoch = payload['epoch']
    if not isinstance(epoch, int) or epoch < 1:
        return 'invalid epoch'
    if [row.get('epoch') for row in payload['history']] != list(range(1, epoch + 1)):
        return 'history does not match epoch'
    best = payload['best_checkpoint']
    score_key = 'validation_mse' if isinstance(best, dict) and best.get('selection_split') == 'validation' else 'test_mse'
    if (not isinstance(best, dict) or 'model_state_dict' not in best
            or not 1 <= best.get('epoch', 0) <= epoch
            or not np.isfinite(best.get(score_key, float('nan')))):
        return 'invalid best checkpoint'
    return None

def find_resume_checkpoint(roots, expected, explicit_path=None):
    if explicit_path is not None:
        candidates = [Path(explicit_path)]
        if not candidates[0].is_file():
            raise FileNotFoundError(f'RESUME_PATH not found: {explicit_path}')
    else:
        candidates = set()
        for root in roots:
            root = Path(root)
            if root.is_dir():
                for pattern in ('*checkpoint*.pt', '*checkpoint*.pth', 'best_model.pt',
                                'best_until_epoch_*.pt'):
                    candidates.update(root.rglob(pattern))
        candidates = sorted(candidates, key=lambda p: str(p))
    selected, selected_path = None, None
    for path in candidates:
        try:
            # New resume files use zip-based torch.save; mmap does not upload weights to the GPU.
            payload = torch.load(path, map_location='cpu', weights_only=True, mmap=True)
            problem = resume_problem(payload, expected)
        except Exception as exc:
            payload, problem = None, f'cannot read: {exc}'
        if problem:
            if explicit_path is not None:
                raise ValueError(f'Cannot resume {path}: {problem}')
            print(f'Skipping {path.name}: {problem}')
            continue
        if selected is None or payload['epoch'] > selected['epoch']:
            selected, selected_path = payload, path
    return selected_path, selected

def seed_everything(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def load_data(data_dir, dataset, device, batch_size=512, test_batch_size=512,
              max_gpus=2, shuffle=False, seed=42):
    """Validate splits, upload one bank per device, then release CPU entity lists."""
    data_dir = Path(data_dir)
    train_data = FourSourceSplit(data_dir / 'train.pt', 'train', dataset)
    test_data = FourSourceSplit(data_dir / 'test.pt', 'test', dataset)
    cpu_tables, ligand_map, protein_map = build_cpu_tables((train_data, test_data))
    devices = execution_devices(device, use_data_parallel=max_gpus > 1, max_gpus=max_gpus)
    store = DeviceFourSourceStore(cpu_tables, devices, ligand_map, protein_map)
    train_batches = IndexBatches(train_data, store, batch_size, shuffle, seed)
    test_batches = IndexBatches(test_data, store, test_batch_size, False, seed)
    train_data.data = test_data.data = None
    print(f'{dataset.upper()}: {len(train_data):,} train / {len(test_data):,} test')
    print('Devices:', [str(d) for d in devices], '| global batch:', batch_size)
    return train_data, test_data, store, train_batches, test_batches
